"""Typed RPC generator with fixed fields and bounded caller-owned response buffers.

The JSON holds bindings, not wire C layouts. No sizeof(native struct), native
pointer, or native enum is ever put directly on the wire.
"""
import json
import re

TYPES = {'u32': ('uint32_t', 4), 'i32': ('int32_t', 4),
         'u64': ('uint64_t', 8), 'i64': ('int64_t', 8), 'f32': ('float', 4),
         'bytes': ('unsigned char', 1), 'cstring': ('char', 1)}
NOTICE = '/* Generated by scripts/generate_rpc.py; do not edit. */'

def fields_decl(fields):
    return [f"  {TYPES[f['type']][0]} {f['name']}" +
            (f"[{f['count']}]" if 'count' in f else '') + ';' for f in fields] or ['  unsigned char unused;']

def size(fields):
    return sum(TYPES[f['type']][1] * f.get('count', 1) for f in fields)

def codec(fields, obj, wire, encode):
    lines = []; offset = 0
    for f in fields:
        name, typ = f['name'], f['type']; count = f.get('count', 1); n = TYPES[typ][1]
        expr = f'{obj}.{name}'
        if typ in ('bytes', 'cstring'):
            lines.append(f'  memcpy({wire}+{offset}, {expr}, {count});' if encode else
                         f'  memcpy({expr}, {wire}+{offset}, {count});')
        else:
            for i in range(count):
                value = expr + (f'[{i}]' if 'count' in f else '')
                pos = offset + i*n
                if typ == 'f32':
                    lines.append(f'  {{ uint32_t bits; ' +
                        (f'memcpy(&bits, &{value}, 4); put32({wire}+{pos}, bits);' if encode else
                         f'bits=get32({wire}+{pos}); memcpy(&{value}, &bits, 4);') + ' }')
                elif encode: lines.append(f'  put{n*8}({wire}+{pos}, {value});')
                else: lines.append(f'  {value}=({TYPES[typ][0]})get{n*8}({wire}+{pos});')
        offset += count*n
    return lines

def validate(schema):
    if schema.get('schema_version') != 2: raise ValueError('schema_version must be 2')
    if len(set(schema['operations'].values())) != len(schema['operations']): raise ValueError('duplicate opcode')
    # Reviewed planning metadata is kept separate from generated RPC capability.
    # Every Graph/IPC API must have exactly one stage with explicit prerequisites.
    plan=schema.get('graph_ipc_plan')
    if plan:
        stages={}
        api_names={api['name'] for api in schema['apis']}
        for stage in plan['stages']:
            sid=stage['id']
            if (sid in stages or stage['family'] not in ('graph','ipc') or
                not all(stage.get(k) for k in ('title','missing','acceptance')) or
                any(dep not in stages for dep in stage['depends_on']) or
                any(api not in api_names for api in stage.get('prerequisite_apis',[]))):
                raise ValueError('invalid or unordered Graph/IPC stage: '+sid)
            stages[sid]=stage
        for api in schema['apis']:
            sid=api.get('contract_stage')
            if api['family'] in ('graph','ipc'):
                if sid not in stages or stages[sid]['family']!=api['family']:
                    raise ValueError('Graph/IPC API lacks matching contract stage: '+api['name'])
            elif sid:
                raise ValueError('unexpected Graph/IPC stage: '+api['name'])
    seen = set(); codes = set()
    for r in schema['typed_rpc']:
        if r['name'] in seen or r['opcode'] in codes: raise ValueError('duplicate typed RPC')
        seen.add(r['name']); codes.add(r['opcode'])
        if schema['operations'].get(r['operation']) != r['opcode']: raise ValueError('opcode mismatch')
        for group in ('request', 'response'):
            names = set()
            for f in r[group]:
                if not re.fullmatch(r'[a-zA-Z_]\w*', f['name']) or f['name'] in names: raise ValueError('invalid field name')
                names.add(f['name'])
                if f['type'] not in TYPES or not 1 <= f.get('count', 1) <= 4096: raise ValueError('invalid wire field')
                if f['type']=='cstring' and 'count' not in f: raise ValueError('cstring requires a fixed capacity')
            if size(r[group]) > 16384: raise ValueError('fixed RPC too large')
        if 'request_buffer' in r:
            b=r['request_buffer']
            if (not re.fullmatch(r'[a-zA-Z_]\w*',b['name']) or
                b['name'] in {f['name'] for f in r['request']} or
                not any(f['name']==b['size_from'] and f['type']=='u64' and 'count' not in f for f in r['request']) or
                not 1<=b['max_bytes']<=64*1024*1024-16384 or r.get('request_array') or r.get('response_array')):
                raise ValueError('invalid bounded request buffer')
        if 'response_buffer' in r:
            b = r['response_buffer']
            if (b['name'] in {f['name'] for f in r['response']} or
                not re.fullmatch(r'[a-zA-Z_]\w*', b['name']) or
                not any(f['name'] == b['size_from'] and f['type'] == 'u64' and 'count' not in f for f in r['request']) or
                not 1 <= b['max_bytes'] <= 64*1024*1024-128-size(r['response'])):
                raise ValueError('invalid caller-owned response buffer')
        for key in ('request_array','response_array'):
            if key not in r: continue
            a=r[key]
            if (a.get('type')!='u64' or not re.fullmatch(r'[a-zA-Z_]\w*',a['name']) or
                a['name'] in {f['name'] for f in r['request' if key=='request_array' else 'response']} or
                not any(f['name']==a['size_from'] and f['type']=='u64' and 'count' not in f for f in r['request']) or
                not 1<=a['max_count']<=(64*1024*1024-16384)//8 or r.get('response_buffer')):
                raise ValueError('invalid bounded u64 array')
    names = set()
    for api in schema['apis']:
        if api['name'] in names: raise ValueError('duplicate API')
        names.add(api['name'])
        if api['status'] not in ('IMPLEMENTED','PARTIAL_IMPLEMENTED','UNSUPPORTED','NOT_IMPLEMENTED','BLOCKED','OUT_OF_SCOPE'): raise ValueError('invalid status')
        if api['status']=='PARTIAL_IMPLEMENTED':
            review=api.get('closure', {})
            if not all(review.get(k) for k in ('gap','fix','acceptance')):
                raise ValueError('PARTIAL requires a concrete gap, fix and acceptance: '+api['name'])
        if api['status'] in ('BLOCKED','OUT_OF_SCOPE') and not api.get('blocker'):
            raise ValueError('terminal scope status requires a reason: '+api['name'])
        for p in api['parameters']:
            if p['kind'] not in schema['types'] or p['direction'] not in ('in','out','inout','unknown'): raise ValueError('invalid parameter')
        if api['implementation']=='generated_local':
            if api.get('wrapper') or api.get('local_error',{}).get('field') not in ('name','description'):
                raise ValueError('invalid generated local API: '+api['name'])
        if api.get('wrapper'):
            if api['wrapper']['rpc'] not in seen: raise ValueError('missing RPC')
            if any(p['direction']=='unknown' or p['length']=='review_required' or p['mapping']=='review_required' for p in api['parameters']):
                raise ValueError('generated API has unreviewed parameters: '+api['name'])
            params=', '.join(p['c_type']+' '+p['name'] for p in api['parameters']) or 'void'
            prototype=f"{api['return_type']} {api['name']}({params});"
            if re.sub(r'\s+','',prototype) != re.sub(r'\s+','',api['signature']):
                raise ValueError('wrapper parameter/signature drift: '+api['name'])
            rpc=next(r for r in schema['typed_rpc'] if r['name']==api['wrapper']['rpc'])
            if set(api['wrapper'].get('inputs',{})) != {f['name'] for f in rpc['request']} | ({rpc['request_array']['name']} if rpc.get('request_array') else set()) | ({rpc['request_buffer']['name']} if rpc.get('request_buffer') else set()): raise ValueError('wrapper request mapping incomplete')
            if api['wrapper'].get('native_status') and not any(f['name']==api['wrapper']['native_status'] and f['type']=='u32' for f in rpc['response']):
                raise ValueError('native_status requires a u32 response field')

def generate(root, schema, check):
    validate(schema)
    files = {}; header = [NOTICE, '#ifndef MLU_TYPED_API_H', '#define MLU_TYPED_API_H']
    opcodes=[NOTICE]; client=[NOTICE]; server=[NOTICE]; backend=[NOTICE]; valid=[NOTICE]; decls=[NOTICE]
    for r in schema['typed_rpc']:
        if r.get('request_buffer'):
            from buffer_codegen import generate_buffer_rpc
            generate_buffer_rpc(r,header,opcodes,client,server,backend,valid,decls,fields_decl,size,codec)
            continue
        if r.get('request_array') or r.get('response_array'):
            from array_codegen import generate_array_rpc
            generate_array_rpc(r,header,opcodes,client,server,backend,valid,decls,fields_decl,size,codec)
            continue
        name=r['name']; op='MLU_OP_'+r['operation']; req=r['request']; res=r['response']
        buffer=r.get('response_buffer')
        count_offset=sum(TYPES[f['type']][1]*f.get('count',1) for f in req[:next((i for i,f in enumerate(req) if buffer and f['name']==buffer['size_from']),0)])
        opcodes.append(f"{op} = {r['opcode']},")
        for direction, fs in [('request',req),('response',res)]:
            header += ['typedef struct {', *fields_decl(fs)]
            if direction=='response' and buffer: header += [f"  unsigned char *{buffer['name']}; /* caller-owned, request.{buffer['size_from']} bytes */"]
            header += [f'}} mlu_api_{name}_{direction};']
        header += [f'int mlu_remote_api_{name}(mlu_remote_context *, const mlu_api_{name}_request *, mlu_api_{name}_response *);']
        conditions=[f'n == {size(res)}']; offset=0
        if buffer:
            conditions=[f'request_len == {size(req)}', f'get64(request+{count_offset}) <= {buffer["max_bytes"]}u',
                        f'n == {size(res)} + get64(request+{count_offset})']
        for f in res:
            if f['type']=='cstring': conditions.append(f'memchr(p+{offset},0,{f["count"]}) != NULL')
            offset+=TYPES[f['type']][1]*f.get('count',1)
        valid += [f'case {op}: return '+ ' && '.join(conditions)+';']
        client += [f'int mlu_remote_api_{name}(mlu_remote_context *ctx, const mlu_api_{name}_request *request, mlu_api_{name}_response *response) {{',
                   '  if (!ctx || !request || !response) return MLU_REMOTE_BAD_LENGTH;',
                   '  if (!(ctx->capabilities & MLU_CAP_TYPED_API)) return MLU_REMOTE_UNSUPPORTED;',
                   f'  unsigned char p[{max(1,size(req))}];', '  unsigned char *e=NULL; uint32_t n=0;',
                   '  mlu_api_'+name+'_request in=*request; (void)in;', *codec(req,'in','p',True),
                   *([f'  if(in.{buffer["size_from"]}>{buffer["max_bytes"]}u || (in.{buffer["size_from"]} && !response->{buffer["name"]})) return MLU_REMOTE_BAD_LENGTH;'] if buffer else []),
                   f'  int st=rpc(ctx,{op},p,{size(req)},&e,&n);',
                   f'  if (!st) {{ mlu_api_{name}_response out={{0}};', *codec(res,'out','e',False),
                   *([f'    out.{buffer["name"]}=response->{buffer["name"]}; if(in.{buffer["size_from"]}) memcpy(out.{buffer["name"]},e+{size(res)},in.{buffer["size_from"]});'] if buffer else []),
                   '    *response=out;', '  } free(e); return st;', '}']
        server += [f'case {op}: {{', f'  if(n!={size(req)}) return send_response(fd,op,req,MLU_REMOTE_BAD_LENGTH,NULL,0);',
                   f'  mlu_api_{name}_request in={{0}}; mlu_api_{name}_response result={{0}};',
                   *codec(req,'in','p',False),
                   *[f'  if(!memchr(in.{f["name"]},0,{f["count"]})) return send_response(fd,op,req,MLU_REMOTE_BAD_LENGTH,NULL,0);' for f in req if f['type']=='cstring'],
                   *([f'  if(in.{buffer["size_from"]}>{buffer["max_bytes"]}u) return send_response(fd,op,req,MLU_REMOTE_BAD_LENGTH,NULL,0);',
                      f'  uint32_t encoded_size={size(res)}+(uint32_t)in.{buffer["size_from"]};',
                      '  unsigned char *encoded=malloc(encoded_size ? encoded_size : 1);',
                      '  if(!encoded) return send_response(fd,op,req,CN_ERROR_SYSTEM_OUT_OF_MEMORY,NULL,0);',
                      f'  result.{buffer["name"]}=encoded+{size(res)};'] if buffer else []),
                   f'  st=mlu_backend_api_{name}(s,&in,&result);',
                   *([] if buffer else [f'  unsigned char encoded[{max(1,size(res))}];']), *codec(res,'result','encoded',True),
                   *(['  int sent=send_response(fd,op,req,(uint32_t)st,st ? NULL : encoded,st ? 0 : encoded_size);',
                      '  free(encoded); return sent;'] if buffer else [f'  return send_response(fd,op,req,(uint32_t)st,st ? NULL : encoded,st ? 0 : {size(res)});']), '}']
        decl=f'int mlu_backend_api_{name}(mlu_backend_session *s, const mlu_api_{name}_request *in, mlu_api_{name}_response *out)'
        decls += [decl+';']
        backend += [decl+' {',
                    *['  '+x for x in r['backend_binding']], '}']
    header += ['#endif']
    files.update({'typed_api.h':header,'typed_opcodes.inc':opcodes,'typed_rpc_client.inc':client,
                  'typed_rpc_server.inc':server,'typed_backend.inc':backend,'typed_success.inc':valid,'typed_backend_decls.inc':decls})
    for lib, filename in [('CNRT','cnrt_api.inc'),('CNDrv','cndrv_api.inc')]:
        lines=[NOTICE]
        for a in schema['apis']:
            if a['library'] != lib or not a.get('wrapper'): continue
            w=a['wrapper']; rpc=w['rpc']; rt=lib=='CNRT'
            decl=', '.join(p['c_type']+' '+p['name'] for p in a['parameters']) or 'void'
            lines += [f"{a['return_type']} {a['name']}({decl}) {{", '  ENTER();']
            if not rt: lines += ['  CURRENT();' if w.get('current') else '  INIT();']
            required=w.get('required',[p['name'] for p in a['parameters'] if p['direction']=='out'])
            if required: lines += ['  if ('+' || '.join('!'+p for p in required)+f") RETURN({'cnrtErrorArgsInvalid' if rt else 'CN_ERROR_INVALID_VALUE'});"]
            lines += ['  '+x for x in w.get('local_prepare',[])]
            if rt: lines += ['  CONNECT();']
            lines += ['  '+x for x in w.get('prepare',[])]
            lines += [f'  mlu_api_{rpc}_request in={{0}}; mlu_api_{rpc}_response out={{0}};']
            rpc_fields={field['name']:field for spec in schema['typed_rpc'] if spec['name']==rpc for field in spec['request']}
            rpc_spec=next(spec for spec in schema['typed_rpc'] if spec['name']==rpc)
            if rpc_spec.get('request_array'):
                rpc_fields[rpc_spec['request_array']['name']]={'type':'u64'}
            if rpc_spec.get('request_buffer'):
                rpc_fields[rpc_spec['request_buffer']['name']]={'type':'bytes'}
            for k,v in w.get('inputs',{}).items():
                f=rpc_fields[k]
                if f['type']=='cstring':
                    lines += [f'  size_t {k}_length=strnlen({v},{f["count"]});',
                              f'  if({k}_length=={f["count"]}) RETURN({"cnrtErrorArgsInvalid" if rt else "CN_ERROR_INVALID_VALUE"});',
                              f'  memcpy(in.{k},{v},{k}_length+1);']
                elif 'count' in f: lines += [f'  memcpy(in.{k},{v},sizeof(in.{k}));']
                else: lines += [f'  in.{k}={v};']
            session=w.get('session','ctx' if rt else 'c->remote' if w.get('current') else 'control')
            lines += ['  '+x for x in w.get('response_prepare',[])]
            lines += [f'  int st=mlu_remote_api_{rpc}({session},&in,&out);', '  if (!st) {']
            lines += ['    '+x for x in w.get('outputs',[])]
            if w.get('native_status'): lines += [f'    st=(int)out.{w["native_status"]};']
            lines += ['  }', *['  '+x for x in w.get('cleanup',[])],
                      f"  RETURN({'status' if rt else 'result'}(st));", '}']
        files[filename]=lines
        exports=[a['name'] for a in schema['apis'] if a['library']==lib and a['implementation']!='none']
        exports+=schema.get('extra_exports',{}).get(lib,[])
        files[lib.lower()+'_exports.map']=['{ global:',*['  '+name+';' for name in sorted(exports)],'local: *; };']
    manifest=[dict(name=a['name'],library=a['library'],rpc=a.get('wrapper',{}).get('rpc'),status=a['status'],implementation=a['implementation'])
              for a in schema['apis'] if a['implementation']!='none']
    files['api_manifest.json']=json.dumps(manifest,indent=2)+'\n'
    files['typed_test_plan.json']=json.dumps([dict(name=r['name'],opcode=r['opcode'],request_bytes=size(r['request']),response_bytes=size(r['response']), **{k:r[k] for k in ('request_buffer','response_buffer','request_array','response_array') if k in r}) for r in schema['typed_rpc']],indent=2)+'\n'
    # Editable scaffolding is emitted into build; semantic assertions must be
    # filled in by the author before adding reviewed evidence to the ledger.
    files['family_test_template.c']=[NOTICE,'#include <assert.h>','#include <cnrt.h>','#include <cn_api.h>',
        '/* Add native and remote value/ordering assertions, not just status. */',
        *[f"/* {a['name']}: {a['family']}; {a['signature']} */" for a in schema['apis'] if a.get('wrapper')]]
    from error_codegen import generate_errors
    files.update(generate_errors(root, schema))
    for name,lines in files.items():
        content=lines if isinstance(lines,str) else '\n'.join(lines)+'\n'
        path=root/('include/generated' if name in ('typed_api.h','typed_opcodes.inc') else 'build/generated')/name
        if check:
            if not path.exists() or path.read_text()!=content: raise SystemExit('out of date: '+str(path))
        else: path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
    print(f"typed schema: {len(schema['apis'])} APIs, {len(schema['typed_rpc'])} RPC codecs/dispatch/bindings, "
          f"{sum(bool(a.get('wrapper')) for a in schema['apis'])} public wrappers")
