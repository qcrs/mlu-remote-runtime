#!/usr/bin/env python3
"""Generate object RPCs and typed API plumbing; lifecycle policy stays manual."""
import json,re,argparse
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(); p.add_argument('--check',action='store_true'); args=p.parse_args()
schema=json.loads((root/'schema/mlu_api_schema.json').read_text())
rows=schema['simple_rpc']
protocol=(root/'include/remote_protocol.h').read_text()
declared={name:int(value) for name,value in re.findall(r'MLU_OP_(\w+)\s*=\s*(\d+)',protocol)}
typed={r['operation']:r['opcode'] for r in schema.get('typed_rpc',[])}
if declared.keys() & typed.keys(): raise SystemExit('typed opcode also manually declared')
declared.update(typed)
if declared!=schema['operations'] or len(set(declared.values()))!=len(declared): raise SystemExit('schema/protocol opcode mismatch')
client=['/* Generated by scripts/generate_rpc.py; do not edit. */']
server=client.copy()
seen=set(); seen_ops=set()
for row in rows:
    name,op,backend=row['client'],row['operation'],row['backend']
    if name in seen or op in seen_ops or op not in schema['operations'] or not re.fullmatch(r'mlu_remote_\w+',name) or not re.fullmatch(r'mlu_backend_\w+',backend): raise SystemExit('invalid simple_rpc schema')
    seen.add(name); seen_ops.add(op)
    client.append(f'int {name}(mlu_remote_context *ctx, uint64_t id) {{ return id_call(ctx, MLU_OP_{op}, id); }}')
    server.extend([f'case MLU_OP_{op}:',
        '  if (n != 8) return send_response(fd, op, req, MLU_REMOTE_BAD_LENGTH, NULL, 0);',
        f'  st = {backend}(s, get64(p));',
        '  return send_response(fd, op, req, (uint32_t)st, NULL, 0);'])
for file,lines in [('simple_rpc_client.inc',client),('simple_rpc_server.inc',server)]:
    path=root/'build/generated'/file; content='\n'.join(lines)+'\n'
    if args.check:
        if not path.exists() or path.read_text()!=content: raise SystemExit(f'out of date: {path}')
    else:
        path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
print(f'simple RPC schema: {len(rows)} generated client wrappers + server cases')

# Imported only after the legacy generation path, so the core-only build keeps
# its original no-SDK requirement.
from api_codegen import generate
generate(root, schema, args.check)
